const adminMessages: Record<AdminLocale, Record<string, string>> = {
  zh: zhMessages,
  ko: koMessages,
  en: enMessages
};

export async function getAdminLocale() {
  const cookieStore = await cookies();
  const cookieLocale = cookieStore.get(adminLocaleCookieName)?.value;

  return isAdminLocale(cookieLocale) ? cookieLocale : defaultAdminLocale;
}

export async function getAdminI18n() {
  const locale = await getAdminLocale();

  return {
    locale,
    messages: adminMessages[locale],
    t: createAdminTranslator(adminMessages[locale])
  };
}

export function createAdminTranslator(messages: Record<string, string>) {
  return (key: string, values?: Record<string, string | number>) => {
    const template = messages[key] ?? enMessages[key] ?? key;

    if (!values) {
      return template;
    }

    return Object.entries(values).reduce(
      (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
      template
    );
  };
}

export function getContentLocaleLabel(messages: Record<string, string>, locale: Locale) {
  return createAdminTranslator(messages)(`contentLocale.${locale}`);
}
